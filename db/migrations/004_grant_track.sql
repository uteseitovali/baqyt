-- ============================================================================
-- 004 — грантовый трек Казахстана
--
-- Добавляет необязательный подобъект costs->'grant' = { entThreshold, note }:
-- пороговый балл ЕНТ для допуска к конкурсу на государственный грант.
--
-- Почему внутри существующей колонки costs, а не отдельной таблицей или
-- колонкой: грант — это второй способ оплатить тот же учебный год, то есть
-- часть стоимости программы. Домен (ProgramCosts в src/lib/domain/types.ts)
-- моделирует его именно так, и схема БД повторяет домен один в один — это
-- договорённость миграции 001, нарушать её ради одного поля не нужно.
--
-- ——— Совместимость ————————————————————————————————————————————————————
-- Миграция аддитивная и обратно совместимая, backfill не требуется:
--   • существующие строки без costs->'grant' остаются валидными — проверка
--     срабатывает только когда ключ присутствует;
--   • старый код, не знающий о поле, читает costs как раньше и игнорирует
--     лишний ключ;
--   • новый код читает grant как optional (Zod .optional(), TS grant?:),
--     поэтому старые строки не ломают ни выдачу, ни скоринг;
--   • откат — drop constraint, данные при этом не теряются.
-- Из-за этого миграцию можно применять на работающей базе до выката кода.
--
-- ——— Происхождение порогов ————————————————————————————————————————————
-- Пороговые баллы ЕНТ для допуска к конкурсу грантов устанавливает МНВО РК;
-- правила конкурса — «Об утверждении Правил присуждения образовательного
-- гранта...», ИПС «Әділет», https://adilet.zan.kz/rus/docs/V2300033345.
-- На цикл 2026 года пороги не менялись относительно 2025: 75 —
-- «Педагогические науки» и «Право», 70 — «Здравоохранение», 65 —
-- национальные вузы, 50 — остальные. Конкретные значения по программам
-- лежат в src/lib/data/programs.ts рядом с ссылкой на источник.
-- ============================================================================

alter table programs
  drop constraint if exists programs_costs_grant_shape;

-- Проверка формы, а не наличия: строка без гранта проходит её без изменений.
alter table programs
  add constraint programs_costs_grant_shape check (
    not (costs ? 'grant')
    or (
      jsonb_typeof(costs -> 'grant') = 'object'
      and costs -> 'grant' ? 'entThreshold'
      and costs -> 'grant' ? 'note'
      and jsonb_typeof(costs -> 'grant' -> 'entThreshold') = 'number'
      and jsonb_typeof(costs -> 'grant' -> 'note') = 'string'
      and (costs -> 'grant' ->> 'entThreshold')::numeric between 0 and 140
    )
  );

-- Частичный индекс: «покажи программы с грантовым треком» — это витринный
-- запрос, а строк с грантом заметно меньше половины каталога.
-- Выражение приводится к numeric намеренно: ->> отдаёт текст, и по тексту
-- «100» сортируется раньше «65». Порог сравнивают диапазонами («порог не
-- выше моего балла»), поэтому индексировать нужно число.
create index if not exists programs_grant_track_idx
  on programs (((costs -> 'grant' ->> 'entThreshold')::numeric))
  where costs ? 'grant';
