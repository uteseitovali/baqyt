/* ============================================================================
   ХОРЕОГРАФИЯ — единая ритмическая система движения

   Проблема, которую это решает: анимации в продукте появлялись по месту, у
   каждой был свой duration и своя кривая. Набор независимых эффектов читается
   как небрежность, даже если каждый эффект по отдельности аккуратный.

   Здесь один словарь на всё приложение. Значения совпадают с CSS-токенами
   --dur-* / --ease-* в globals.css: часть движения живёт в CSS (разгон полосок,
   появление карточек), часть в motion/react (герой, кольцо, таймлайн), но
   звучать они обязаны одинаково.

   Общий жест системы: маршрут прочерчивается по направлению движения
   (слева направо, сверху вниз), а вехи приезжают с перелётом и садятся.

   ВАЖНО: глобальный блок prefers-reduced-motion в globals.css гасит только
   CSS-анимации. JS-анимации motion/react он не видит — поэтому каждый
   компонент отсюда обязан спрашивать useReducedMotion() сам.
   ========================================================================= */

type Ease = [number, number, number, number];

/** Длительности в секундах — motion/react принимает секунды, CSS миллисекунды. */
export const DUR = {
  quick: 0.18,
  base: 0.28,
  slow: 0.42,
  /** Прочерчивание маршрута — единственная длинная анимация в системе. */
  draw: 1.15,
} as const;

export const EASE: Record<"out" | "in" | "overshoot", Ease> = {
  /** Вход: быстро стартует, мягко садится. */
  out: [0.22, 1, 0.36, 1],
  /** Выход: короче входа, поэтому уходит резче. */
  in: [0.55, 0, 1, 0.45],
  /** Прилёт вехи: проскакивает цель и возвращается. */
  overshoot: [0.34, 1.56, 0.64, 1],
};

/** Шаг каскада. 30–50 мс — предел, после которого список «разваливается». */
export const STAGGER = {
  tight: 0.035,
  base: 0.045,
  /**
   * Вехи героя: семь вех должны уложиться в ~0.5 с, чтобы вся вводная
   * анимация (линия + посадка последней вехи с пружиной ≈0.65 с) занимала
   * ~1.2 с, а не 1.7. Замерено покадрово, см. RouteMap.tsx.
   */
  waypoint: 0.07,
} as const;

/** Физика прилёта вехи. Пружина, а не кривая: перелёт должен быть честным. */
export const SPRING_WAYPOINT = {
  type: "spring",
  stiffness: 380,
  damping: 17,
  mass: 0.8,
} as const;

/* ——— Готовые варианты для каскадов ————————————————————————————————— */

/** Контейнер списка: сам не движется, только раздаёт детям задержки. */
export const listContainer = {
  hidden: {},
  visible: {
    transition: { staggerChildren: STAGGER.base, delayChildren: 0.06 },
  },
};

/** Элемент списка: приезжает снизу — по направлению чтения маршрута. */
export const listItem = {
  hidden: { opacity: 0, y: 10 },
  visible: {
    opacity: 1,
    y: 0,
    transition: { duration: DUR.base, ease: EASE.out },
  },
};

/** Вертикальная линия маршрута: прочерчивается сверху вниз. */
export const railDraw = {
  hidden: { scaleY: 0 },
  visible: {
    scaleY: 1,
    transition: { duration: DUR.draw * 0.6, ease: EASE.out },
  },
};
