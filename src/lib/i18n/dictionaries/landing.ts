/* ============================================================================
   ТЕКСТ ЛЕНДИНГА (src/app/page.tsx)

   Образец для остальных экранов: один интерфейс формы + одна таблица
   Translations<…>. Форма — контракт для переводчика: что именно нужно
   перевести и в каком количестве. Русский — полный, остальные локали
   заполняются по кусочку.

   Что здесь НЕ лежит:
     • подписи шагов пути (JOURNEY) — они в domain/taxonomy.ts и берутся
       оттуда через taxonomyFor(locale);
     • числа (число программ и стран, «0{n}» у карточек) — это данные, а не
       текст: форматируются в коде.

   Заголовок разбит на две части, потому что «акцентная» половина рисуется
   другим цветом. Если в другом языке фраза делится иначе — меняется только
   граница между lead и accent, разметка остаётся той же.
   ========================================================================= */

export interface LandingText {
  /** Чип над заголовком. */
  intakeChip: string;
  headline: {
    lead: string;
    accent: string;
  };
  lead: string;
  cta: {
    start: string;
    /** Показывается вместо start, если анкета уже заполнена. */
    continue: string;
    demo: string;
    demoHint: string;
  };
  deliverables: {
    heading: string;
    items: { title: string; body: string }[];
  };
  journey: {
    heading: string;
    /** Пояснение к каждому шагу — по id, а не по номеру: порядок шагов не важен. */
    blurbs: Record<StepId, string>;
  };
  honesty: {
    heading: string;
    body: string;
    stats: {
      programs: string;
      countries: string;
      factors: string;
    };
  };
}

